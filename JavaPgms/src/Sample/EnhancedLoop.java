package Sample;

public class EnhancedLoop {

	public static void main(String[] args) {
		//Enhanced for loop
		
		
		int[] numbers = {1,2,3,4,5};
		
		for(int n:numbers) {
			System.out.println(n);
			
		}
		
		String[] words = {"Tharun","Hello","Good" , "Everning"};
		
		for(String Tharun:words) {
			System.out.println(Tharun);
			
			
		}
		

	}

}
